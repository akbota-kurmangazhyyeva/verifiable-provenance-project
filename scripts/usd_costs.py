#!/usr/bin/env python3
"""Dollar cost per record (paper Table 3) and the inclusion-check fit (Eq. 3).

Inputs, all in the repository:
  data/gas_single.csv, data/gas_batch.csv   gas measured by measure_gas.py
  data/prices.json                          gas prices and ETH price, with sources

Outputs:
  data/usd_costs.csv      one row per design, gas and USD for every price scenario
  data/verify_fit.json    coefficients of gas_verify(n) = a + b*log2(n)
  tables/usd_costs.tex    the tabular for Table 3, to paste into the paper

Nothing is measured here; change data/prices.json and rerun to refresh the
dollar figures.
"""

import csv
import json
import math
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from provenance.costs import fit_log2, latex_int, latex_usd, significant, usd

DATA = ROOT / "data"
TABLES = ROOT / "tables"
BATCH_ROWS = (4, 64, 1024)  # batch sizes shown in Table 3
CHECK_ROW = 1024  # batch size of the inclusion-check row


def designs(single: pd.DataFrame, batch: pd.DataFrame) -> list[tuple[str, str, float]]:
    """(key, LaTeX label, gas per record) for every row of Table 3."""
    by_size = batch.set_index("batch_size")
    rows = [
        ("log", "Event-only log", single.loc[single.design == "log", "gas_used"].mean()),
        ("registry", "Registry", single.loc[single.design == "registry", "gas_used"].mean()),
    ]
    rows += [(f"batch_{n}", f"Batched, $n={n}$", by_size.loc[n, "gas_per_record"]) for n in BATCH_ROWS]
    rows.append((f"check_{CHECK_ROW}", f"Check, $n={CHECK_ROW}$", by_size.loc[CHECK_ROW, "verification_gas"]))
    return rows


def latex_table(rows: list[tuple[str, str, float]], prices: dict) -> str:
    scenarios = prices["scenarios"]
    eth = prices["eth_usd"]["value"]
    groups: list[tuple[str, int]] = []
    for scenario in scenarios:
        if groups and groups[-1][0] == scenario["chain"]:
            groups[-1] = (scenario["chain"], groups[-1][1] + 1)
        else:
            groups.append((scenario["chain"], 1))

    lines = [
        "% Generated by scripts/usd_costs.py from data/gas_*.csv and data/prices.json. Do not edit by hand.",
        "\\begin{tabular}{lr" + "r" * len(scenarios) + "}",
        "\\toprule",
        " & & " + " & ".join(f"\\multicolumn{{{width}}}{{c}}{{{name}}}" for name, width in groups) + " \\\\",
    ]
    rules, column = [], 3
    for _, width in groups:
        rules.append(f"\\cmidrule(lr){{{column}-{column + width - 1}}}")
        column += width
    lines.append("".join(rules))
    lines.append(" & & " + " & ".join(scenario["label"] for scenario in scenarios) + " \\\\")
    lines.append("Design & Gas & " + " & ".join(f"{significant(scenario['gwei'])} gwei" for scenario in scenarios) + " \\\\")
    lines.append("\\midrule")
    for key, label, gas in rows:
        if key.startswith("check_"):
            lines.append("\\midrule")
        cells = [latex_usd(usd(gas, scenario["gwei"], eth)) for scenario in scenarios]
        lines.append(f"{label} & {latex_int(gas)} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


def main() -> None:
    single = pd.read_csv(DATA / "gas_single.csv")
    batch = pd.read_csv(DATA / "gas_batch.csv")
    prices = json.loads((DATA / "prices.json").read_text(encoding="utf-8"))
    eth = prices["eth_usd"]["value"]
    rows = designs(single, batch)

    with (DATA / "usd_costs.csv").open("w", newline="") as output:
        writer = csv.writer(output)
        writer.writerow(["design", "gas", *[f"usd_{scenario['key']}" for scenario in prices["scenarios"]]])
        for key, _, gas in rows:
            writer.writerow([key, f"{gas:.2f}", *[f"{usd(gas, scenario['gwei'], eth):.3e}" for scenario in prices["scenarios"]]])

    intercept, slope, r_squared = fit_log2(batch.batch_size.tolist(), batch.verification_gas.tolist())
    smallest, largest = batch.verification_gas.iloc[0], batch.verification_gas.iloc[-1]
    fit = {
        "model": "verification_gas = intercept + slope * log2(batch_size)",
        "points": len(batch),
        "batch_sizes": batch.batch_size.tolist(),
        "intercept": intercept,
        "slope": slope,
        "r_squared": r_squared,
        "max_abs_residual": max(abs(gas - (intercept + slope * math.log2(n))) for n, gas in zip(batch.batch_size, batch.verification_gas)),
        "measured_increase_largest_vs_single": largest / smallest - 1,
    }
    (DATA / "verify_fit.json").write_text(json.dumps(fit, indent=2) + "\n")

    TABLES.mkdir(exist_ok=True)
    (TABLES / "usd_costs.tex").write_text(latex_table(rows, prices), encoding="utf-8")

    print(f"ETH/USD {eth} ({prices['eth_usd']['date']})")
    for key, _, gas in rows:
        dollars = ", ".join(f"{scenario['key']}: ${usd(gas, scenario['gwei'], eth):.3g}" for scenario in prices["scenarios"])
        print(f"{key:>12}  {gas:>10,.1f} gas  {dollars}")
    print(
        f"Eq. 3 fit over {fit['points']} batch sizes: gas_verify(n) = {intercept:,.0f} + {slope:,.0f} log2 n "
        f"(R^2 = {r_squared:.4f}, max residual {fit['max_abs_residual']:.0f} gas); "
        f"n={batch.batch_size.iloc[-1]} costs {fit['measured_increase_largest_vs_single']:.1%} more than n=1"
    )


if __name__ == "__main__":
    main()
